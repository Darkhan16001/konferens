function formatTime(value) {

    const minutes = Math.floor(value / 60);

    const remainder = value % 60;

    return (

        String(minutes).padStart(2, "0") +

        ":" +

        String(remainder).padStart(2, "0")

    );

}

function updateTimer() {

    $("timer").textContent = formatTime(seconds);

    $("timer").classList.toggle(

        "running",

        running

    );

    $("timer").classList.toggle(

        "warning",

        seconds <= 60

    );

    $("timer").title = running

        ? "Таймерді тоқтату"

        : "Таймерді бастау";

}


// ТАЙМЕРДІ БАСТАУ ЖӘНЕ ТОҚТАТУ

function toggleTimer() {

    if (running) {

        seconds = Math.max(

            0,

            Math.ceil(

                (deadline - Date.now()) / 1000

            )

        );

        running = false;

    } else {

        if (seconds <= 0) {

            seconds = TOTAL_TIME;

        }

        deadline =

            Date.now() + seconds * 1000;

        running = true;

    }

    updateTimer();

}

$("timer").onclick = toggleTimer;


// УАҚЫТТЫ ЖАҢАРТУ

setInterval(() => {

    if (!running) return;

    seconds = Math.max(

        0,

        Math.ceil(

            (deadline - Date.now()) / 1000

        )

    );

    if (seconds === 0) {

        running = false;

    }

    updateTimer();

}, 200);


