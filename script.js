// 25% — 100% — 300%
// =============================================

function updateZoom(center = false) {

    const viewportWidth = stage.clientWidth;

    const viewportHeight = stage.clientHeight;

    if (

        viewportWidth <= 0 ||

        viewportHeight <= 0

    ) return;


    // АЛДЫҢҒЫ МАСШТАБТЫҢ ОРТАЛЫҒЫ

    const oldWidth = zoomFrame.offsetWidth;

    const oldHeight = zoomFrame.offsetHeight;

    let focusX = 0.5;

    let focusY = 0.5;

    if (!center && oldWidth && oldHeight) {

        focusX = (

            stage.scrollLeft +

            viewportWidth / 2 -

            zoomFrame.offsetLeft

        ) / oldWidth;

        focusY = (

            stage.scrollTop +

            viewportHeight / 2 -

            zoomFrame.offsetTop

        ) / oldHeight;

        focusX = Math.max(
            0,
            Math.min(1, focusX)
        );

        focusY = Math.max(
            0,
            Math.min(1, focusY)
        );

    }


    // 100% — ҚАЛЫПТЫ ӨЛШЕМ

    const fitScale = Math.max(

        0.001,

        Math.min(

            (viewportWidth - 12) / SLIDE_WIDTH,

            (viewportHeight - 12) / SLIDE_HEIGHT

        )

    );


    // МАСШТАБТЫҢ ШЕКТЕРІ

    zoom = Math.max(

        MIN_ZOOM,

        Math.min(MAX_ZOOM, zoom)

    );


    // НАҚТЫ ҮЛКЕЙТУ

    actualScale =

        fitScale * zoom / 100;

    const newWidth = Math.ceil(

        SLIDE_WIDTH * actualScale

    );

    const newHeight = Math.ceil(

        SLIDE_HEIGHT * actualScale

    );


    // БҮКІЛ СЛАЙД БІРГЕ ҮЛКЕЙЕДІ

    slide.style.transform =

        `scale(${actualScale})`;

    zoomFrame.style.width =

        newWidth + "px";

    zoomFrame.style.height =

        newHeight + "px";


    // ҮЛКЕЙГЕН СЛАЙДҚА ОРЫН АШУ

    workspace.style.width =

        Math.max(

            viewportWidth,

            newWidth + 12

        ) + "px";

    workspace.style.height =

        Math.max(

            viewportHeight,

            newHeight + 12

        ) + "px";


    // ҮЛКЕЙГЕН СЛАЙДТЫ ЖЫЛЖЫТУ

    const canPan =

        workspace.offsetWidth > viewportWidth ||

        workspace.offsetHeight > viewportHeight;

    stage.classList.toggle(

        "zoomed",

        canPan

    );


    // СЛАЙД ОРТАЛЫҒЫН САҚТАУ

    stage.scrollLeft =

        zoomFrame.offsetLeft +

        focusX * newWidth -

        viewportWidth / 2;

    stage.scrollTop =

        zoomFrame.offsetTop +

        focusY * newHeight -

        viewportHeight / 2;


    // БАТЫРМАЛАРДЫ ЖАҢАРТУ

    $("zoomValue").textContent =

        zoom + "%";

    $("zoomSlider").value = zoom;

    $("zoomOut").disabled =

        zoom <= MIN_ZOOM;

    $("zoomIn").disabled =

        zoom >= MAX_ZOOM;

    $("zoomMax").disabled =

        zoom >= MAX_ZOOM;

}


// =============================================
// МАСШТАБ МӘНІ
// =============================================

function setZoom(value, center = false) {

    zoom = Math.max(

        MIN_ZOOM,

        Math.min(MAX_ZOOM, Number(value))

    );

    updateZoom(center);

}


