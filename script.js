document.addEventListener("keydown", event => {

    if (document.querySelector("dialog[open]")) {

        return;

    }

    if (event.ctrlKey || event.metaKey || event.altKey) {

        return;

    }

    if (

        ["INPUT", "TEXTAREA", "SELECT"]

            .includes(event.target.tagName)

    ) {

        return;

    }


    // SHIFT + БАҒЫТТАУ БАТЫРМАЛАРЫ
    // ҮЛКЕЙТІЛГЕН СЛАЙДТЫ ҚОЗҒАЛТУ

    if (event.shiftKey) {

        const directions = {

            ArrowLeft: [-100, 0],

            ArrowRight: [100, 0],

            ArrowUp: [0, -100],

            ArrowDown: [0, 100]

        };

        if (directions[event.key]) {

            event.preventDefault();

            stage.scrollBy(

                directions[event.key][0],

                directions[event.key][1]

            );

            return;

        }

    }


    // КЕЛЕСІ СЛАЙД

    if (

        ["ArrowRight", "ArrowDown", "PageDown"]

            .includes(event.key)

    ) {

        event.preventDefault();

        nextSlide();

    }


    // АЛДЫҢҒЫ СЛАЙД

    if (

        ["ArrowLeft", "ArrowUp", "PageUp"]

            .includes(event.key)

    ) {

        event.preventDefault();

        prevSlide();

    }


    // ҮЛКЕЙТУ

    if (event.key === "+" || event.key === "=") {

        event.preventDefault();

        setZoom(zoom + 5);

    }


    // КІШІРЕЙТУ

    if (event.key === "-") {

        event.preventDefault();

        setZoom(zoom - 5);

    }


    // ҚАЛЫПТЫ 100%

    if (event.key === "0") {

        event.preventDefault();

        setZoom(100, true);

    }


    // МАКСИМАЛДЫ 300%

    if (event.key.toLowerCase() === "m") {

        setZoom(300, true);

    }


    // ТОЛЫҚ ЭКРАН

    if (event.key.toLowerCase() === "f") {

        toggleFullscreen();

    }


    // БАЯНДАМА

    if (event.key.toLowerCase() === "n") {

        $("notesDialog").showModal();

    }


    // ТАЙМЕР

    if (

        event.code === "Space" &&

        !["BUTTON", "A"].includes(event.target.tagName)

    ) {

        event.preventDefault();

        toggleTimer();

    }


    // БІРІНШІ СЛАЙД

    if (event.key === "Home") {

        event.preventDefault();

        current = 0;

        render();

    }


    // СОҢҒЫ СЛАЙД

    if (event.key === "End") {

        event.preventDefault();

        current = slides.length - 1;

        render();

    }


    // ESC

    if (event.key === "Escape") {

        $("menu").hidden = true;

    }

});


