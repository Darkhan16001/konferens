function createPhoto(item, index) {

    const figure = document.createElement("figure");

    figure.className = "visual";

    const wrap = document.createElement("div");

    wrap.className = "image-wrap";

    const image = document.createElement("img");

    image.alt = item.caption;

    image.draggable = false;

    image.decoding = "async";


    // ФОТОНЫҢ ҮШ БАЛАМА СІЛТЕМЕСІ

    const urls = [

        photoURL(item),

        `images/photo${index + 1}.jpg`,

        "https://commons.wikimedia.org/wiki/Special:FilePath/" +

        encodeURIComponent(item.photo)

    ];

    let attempt = 0;

    image.addEventListener("error", () => {

        attempt++;

        if (attempt < urls.length) {

            image.src = urls[attempt];

        } else {

            image.replaceWith(createFallback());

        }

    });

    wrap.appendChild(image);

    image.src = urls[0];


    // ФОТО НӨМІРІ

    const badge = document.createElement("div");

    badge.className = "photo-index";

    badge.textContent =

        "GREEN BIOTECH / " +

        String(index + 1).padStart(2, "0");

    wrap.appendChild(badge);

    figure.appendChild(wrap);


    // ФОТО АСТЫНДАҒЫ АҚПАРАТ

    const caption = document.createElement("figcaption");

    caption.className = "photo-label";

    caption.innerHTML = `

        ${item.caption}

        <span class="photo-credit">

            <a href="${creditURL(item)}"
               target="_blank"
               rel="noopener noreferrer">

                ${item.photographer} · Wikimedia Commons
                · ${item.license}

            </a>

        </span>

    `;

    figure.appendChild(caption);

    return figure;

}


